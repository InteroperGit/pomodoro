import * as React from 'react';

type Props = {
    pomodoroTimeElapsed: number;
};

/**
 * Компонент PomodoroClock — визуальный таймер для отображения прошедшего времени в формате MM:SS.
 *
 * Props:
 * - pomodoroTimeElapsed (number): количество прошедших секунд с начала текущей помодоро-сессии.
 *
 * Логика:
 * - Рассчитывает количество минут и секунд из общего числа секунд.
 * - Форматирует время в строку с ведущими нулями для единообразного отображения.
 *   Например, 5 минут и 3 секунды -> "05:03".
 *
 * Визуализация:
 * - Время выводится крупным шрифтом (6rem) с тонким начертанием и белым цветом с прозрачностью 90%.
 * - Центрируется горизонтально и вертикально с помощью flexbox.
 *
 * Особенности:
 * - Строгая типизация пропсов через TypeScript.
 * - Компактная, легко переиспользуемая визуализация времени.
 * - Чистый UI без лишних деталей, что соответствует минималистичному дизайну таймера.
 *
 * Возможные улучшения:
 * - Добавить плавную анимацию изменения времени.
 * - Добавить поддержку паузы, предупреждения по времени (цвета, звуки).
 * - Сделать настраиваемый формат отображения (например, показывать часы).
 * - Поддержать локализацию и кастомные стили через пропсы.
 *
 * Итог:
 * - Простой и эффективный компонент для отображения оставшегося или прошедшего времени в Pomodoro-технике.
 */
const PomodoroClock = ({
        pomodoroTimeElapsed,
    }: Props) => {

    const minutes = Math.floor(pomodoroTimeElapsed / 60);
    const seconds = pomodoroTimeElapsed % 60;

    const formattedTime = `${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;

    return (
        <div className="flex justify-center items-center">
            <div className="text-white/90 text-[6rem] leading-none font-thin">
                { formattedTime }
            </div>
        </div>
    );
};

export default PomodoroClock;